import { createHmac } from "node:crypto";

/**
 * Writes the local Supabase keys into `.env.local`.
 *
 * ## Why keys are generated rather than hard-coded
 *
 * PostgREST validates the JWT on every request against the secret the compose
 * file gives it, so an `anon` key from a hosted project is simply rejected by a
 * local stack. The local keys have to be signed with the *local* secret, and
 * that secret lives in `docker-compose.supabase.yml` rather than in gitignore'd
 * files — so the honest thing is to derive them from the same constant the
 * stack uses, at the moment the contributor runs it.
 *
 * These keys are for `docker-compose.supabase.yml` and nothing else. They are
 * signed with a secret that is committed in that file, which is fine precisely
 * because the thing they authenticate to is a container on the contributor's own
 * machine. Never point them at anything reachable from a network.
 *
 * Run with `npm run db:keys`.
 */

const SECRET = "super-secret-jwt-token-with-at-least-32-characters-long";
const BASE_URL = "http://127.0.0.1:54330";
const ENV_LOCAL = ".env.local";

function base64url(input: string): string {
  return Buffer.from(input, "utf8")
    .toString("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");
}

function jwt(role: string): string {
  const issuedAt = Math.floor(Date.now() / 1000);
  const header = base64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const payload = base64url(
    JSON.stringify({
      iss: "supabase",
      ref: "local",
      role,
      iat: issuedAt,
      exp: issuedAt + 60 * 60 * 24 * 365,
    }),
  );
  const signature = createHmac("sha256", SECRET).update(`${header}.${payload}`).digest("base64url");

  return `${header}.${payload}.${signature}`;
}

/**
 * Appends or replaces one `KEY=value` line.
 *
 * Rewriting the whole file would clobber whatever the contributor already has
 * in `.env.local` — an admin email, a feature flag — so each line is touched in
 * place and only the six this owns are set.
 */
function upsertLine(contents: string, key: string, value: string): string {
  const line = `${key}=${value}`;
  const pattern = new RegExp(`^${key}=.*$`, "m");

  return pattern.test(contents) ? contents.replace(pattern, line) : `${contents.trimEnd()}\n${line}\n`;
}

async function main(): Promise<void> {
  const { readFile, writeFile } = await import("node:fs/promises");

  let contents = "";

  try {
    contents = await readFile(ENV_LOCAL, "utf8");
  } catch {
    // No `.env.local` yet. Creating one is the normal case for a fresh clone.
  }

  if (contents.trim() !== "" && !contents.includes("LOCAL SUPABASE")) {
    contents = `${contents.trimEnd()}\n\n# ─── LOCAL SUPABASE (generated by npm run db:keys) ─────────────────────\n#\n# Signed with the secret in docker-compose.supabase.yml, for the local\n# PostgREST stack only. They authenticate to nothing reachable from a network.\n`;
  }

  for (const [key, value] of [
    ["SUPABASE_URL", BASE_URL],
    ["SUPABASE_PUBLISHABLE_KEY", jwt("anon")],
    ["SUPABASE_SECRET_KEY", jwt("service_role")],
  ] as const) {
    contents = upsertLine(contents, key, value);
  }

  await writeFile(ENV_LOCAL, contents, "utf8");

  console.log(`Wrote local Supabase keys to ${ENV_LOCAL}`);
  console.log(`  SUPABASE_URL = ${BASE_URL}`);
  console.log("  Keys signed with the local secret. Start the stack with:");
  console.log("    docker compose -f docker-compose.supabase.yml up -d");
}

void main();